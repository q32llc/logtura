import { readFileSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const __dirname = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(__dirname, "..");
const env = readFileSync(resolve(projectRoot, ".env"), "utf8").split("\n").reduce((a,l)=>{const m=l.match(/^([A-Z_]+)=(.*)$/);if(m){let v=m[2];if((v.startsWith('"')&&v.endsWith('"'))||(v.startsWith("'")&&v.endsWith("'")))v=v.slice(1,-1);a[m[1]]=v}return a},{});
const r = spawnSync("pnpm",["wrangler","d1","execute","logtura","--remote","--json","--command","SELECT hex(credentials_encrypted) AS h FROM deploy_targets WHERE id='dpt_vF93cmrBEpRpOiBpMkYIHQ'"],{encoding:"utf8",cwd:projectRoot});
const lines = r.stdout.split("\n");
const start = lines.findIndex(l => l.trim().startsWith("["));
const json = JSON.parse(lines.slice(start).join("\n"));
const h = json[0].results[0].h;
const buf = new Uint8Array(Buffer.from(h, "hex"));
const iv = buf.subarray(0,12), ct = buf.subarray(12);
const keyB64 = env.CREDENTIAL_ENCRYPTION_KEY;
const padded = keyB64.replace(/-/g,"+").replace(/_/g,"/") + "===".slice((keyB64.length+3)%4);
const rawKey = new Uint8Array(Buffer.from(padded,"base64"));
const key = await crypto.subtle.importKey("raw", rawKey, {name:"AES-GCM"}, false, ["decrypt"]);
const pt = await crypto.subtle.decrypt({name:"AES-GCM", iv}, key, ct);
const token = JSON.parse(new TextDecoder().decode(pt)).apiToken;
const { dischargeBundle } = await import(resolve(projectRoot, "src/deploy-targets/fly-macaroon.ts"));
const auth = await dischargeBundle("FlyV1 " + token);
writeFileSync("/tmp/fly-token", auth.replace(/^FlyV1 /, ""));
console.log("wrote /tmp/fly-token");
